#!/usr/bin/env python3
"""Generate INDEX.md and synchronize inventory descriptions; --check writes nothing."""
import argparse
import json
from pathlib import Path
import re
from counts import counts
from gen_routing import CATS

ROOT = Path(__file__).resolve().parent.parent


def outputs():
    inventory = counts()
    skills = {p.name: p for p in (ROOT / "skills").iterdir() if p.is_dir()}
    lines = ["# Skill catalog", "", "Generated by `python3 scripts/sync_catalog.py`. Do not edit by hand.",
             "", f"## Skills ({inventory['skills']})", ""]
    covered = set()
    for category, rows in CATS.items():
        present = [(name, trigger) for name, trigger in rows if name in skills]
        if not present:
            continue
        lines += [f"### {category} ({len(present)})", "", "| Skill | When to load |", "|---|---|"]
        for name, trigger in present:
            lines.append(f"| [{name}](skills/{name}/SKILL.md) | {trigger} |")
            covered.add(name)
        lines.append("")
    if covered != set(skills):
        raise ValueError(f"skills missing from routing map: {sorted(set(skills)-covered)}")
    experimental = sorted(p.parent.name for p in (ROOT / "examples/experimental").glob("*/SKILL.md"))
    lines += [f"## Experimental ({len(experimental)})", "", "Opt-in only; not included in the default skill path.", ""]
    lines += [f"- [{name}](examples/experimental/{name}/SKILL.md)" for name in experimental]
    for key, folder in (("agents", "agents"), ("commands", "commands")):
        lines += ["", f"## {key.title()} ({inventory[key]})", ""]
        lines += [f"- [{p.stem}]({folder}/{p.name})" for p in sorted((ROOT/folder).glob("*.md"))]
    result = {ROOT / "INDEX.md": "\n".join(lines)+"\n"}
    paths = [ROOT/"package.json", ROOT/"gemini-extension.json"]
    paths += sorted(ROOT.glob(".*-plugin/*.json"))
    paths += sorted((ROOT/".pi").glob("*.json"))
    paths += sorted((ROOT/".gemini").glob("*.json"))
    for path in paths:
        data = json.loads(path.read_text())
        if isinstance(data.get("description"), str):
            desc = data["description"]
            for key, number in inventory.items():
                desc = re.sub(r"\b\d+ " + key + r"\b", f"{number} {key}", desc)
            data["description"] = desc
            result[path] = json.dumps(data, indent=2)+"\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.write_text(content)
    if args.check and stale:
        parser.exit(1, "stale generated files: " + ", ".join(stale) + "\n")
    print("catalog current" if args.check else "catalog synchronized")


if __name__ == "__main__":
    main()
